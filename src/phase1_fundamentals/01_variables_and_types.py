"""
Phase 1.1 - Python变量与数据类型
对比C/Java，理解Python的动态类型特性
"""

# ============================================================
# 1. 变量声明 - Python不需要声明类型（动态类型）
# ============================================================

# C: int n = 10;
# Java: int n = 10;
# Python:
n = 10
print(f"n = {n}, type = {type(n)}")
# Python可以随时改变变量类型
n = "hello"  # 这在C/Java中是不允许的
print(f"n = {n}, type = {type(n)}")
# ============================================================
# 2. 基本数据类型
# ============================================================
#f-string（格式化字符串）
# 整数 - 没有大小限制（C的int有范围）
big_num = 10 ** 100  # 10的100次方
print(f"大整数: {big_num}")
# 浮点数
pi = 3.14159265358979
print(f"π = {pi}")

# 布尔值 - 注意大写开头
is_valid = True
has_error = False
print(f"布尔值: {is_valid}, {has_error}")

# 字符串 - Python字符串非常强大
name = "复杂网络"
print(f"字符串长度: {len(name)}")

# 多行字符串
description = """
这是一个复杂网络仿真平台
用于研究网络鲁棒性和级联失效
"""
print(description.strip())  # strip() 去除首尾空白

# ============================================================
# 3. 字符串操作（Python比C/Java方便得多）
# ============================================================

# f-string格式化（Python 3.6+，最推荐的方式）
nodes = 1000
edges = 5000
print(f"网络规模: {nodes}个节点, {edges}条边")
print(f"平均度: {2 * edges / nodes:.2f}")  # :.2f 保留2位小数

# 字符串方法
s = "  Hello, Network Science!  "

print(f"去除空白: '{s.strip()}'")

print(f"转小写: '{s.strip().lower()}'")

print(f"替换: '{s.strip().replace('Hello', '你好')}'")

print(f"分割: {s.strip().split(' ')}")

# ============================================================
# 4. 类型转换
# ============================================================

# C: int x = (int) "123";  // 需要显式转换
# Python:
x = int("123")
y = float("3.14")
z = str(42)
print(f"转换: int='123' -> {x}, float='3.14' -> {y}, str(42) -> '{z}'")

# ============================================================
# 5. Python特有：None（类似Java的null，C的NULL）
# ============================================================

result = None
print(f"None的类型: {type(result)}")
print(f"None是None吗: {result is None}")  # 用 is 判断None，不要用 ==

# ============================================================
# 6. 多重赋值（Python特色）
# ============================================================

# 同时给多个变量赋值
x, y, z = 1, 2, 3
print(f"多重赋值: x={x}, y={y}, z={z}")

# 交换变量（不需要临时变量！）
x, y = y, x
print(f"交换后: x={x}, y={y}")

# ============================================================
# 练习：计算ER随机网络的平均度
# ============================================================

def exercise_er_avg_degree():
    """计算ER随机网络的平均度"""
    N = 1000   # 节点数
    p = 0.01   # 连接概率

    # 平均度 = N * p
    avg_degree = N * p
    print(f"ER网络: N={N}, p={p}, 平均度={avg_degree}")

    # 边数 = N*(N-1)/2 * p
    expected_edges = N * (N - 1) / 2 * p
    print(f"期望边数: {expected_edges:.0f}")

if __name__ == "__main__":
    exercise_er_avg_degree()
